// An item that represents transactions on an alert interface

class alert_seq_item extends uvm_sequence_item;
  // The type of transaction represented by this item. This is set by monitors to report an alert, a
  // ping request, or a signal integrity failure.
  //
  // When the item is being driven, this will always be a ping request or an alert (this is
  // guaranteed when randomising by ping_or_alert_c)
  rand alert_trans_type_e m_trans_type;

  // If this field is nonzero, the driver will cause a signal integrity error of that many cycles
  // when driving this item.
  rand int unsigned m_int_err_cyc;

  // A delay injected by alert_receiver_driver before it actually sends a ping request. This allows
  // the driver to be sent a stream of back-to-back items without locking up the interface.
  rand int unsigned m_ping_delay;

  // The number of cycles the driver should wait before acking an alert (when being an alert
  // receiver) or clearing an alert after it has been acked (when being an alert sender).
  rand int unsigned m_ack_delay;

  // The number of cycles a receiver should continue to assert ack after the sender has dropped
  // alert_p.
  //
  // This only has an effect when acting as an alert receiver.
  rand int unsigned m_ack_stable;

  // The number of cycles to wait before sending an alert.
  //
  // This only has an effect when acting as an alert sender.
  rand int unsigned m_alert_delay;

  // This bit is set on items generated by a monitor that has seen a timeout caused by an
  // alert/escalation sender not responding to a ping.
  bit m_ping_timeout;

  // Generated by alert_monitor: this item shows the current stage of the alert handshake
  alert_handshake_e m_alert_handshake_sta;

  extern function new (string name = "");

  // Constrain delays in the generated item
  extern constraint delay_c;

  // Randomised items (to be driven, rather than items generated by a monitor) should only have
  // transaction types representing a ping request or an alert.
  extern constraint ping_or_alert_c;

  // Constraints on m_int_err_cyc for items randomised for a driver.
  //
  // Normally, we don't want to generate signal integrity errors, so there's a soft constraint that
  // m_int_err_cyc is zero. If this is overridden or disabled, provide a distribution for the length
  // of the signal integrity error.
  extern constraint int_err_cyc_c;

  // Randomised items (to be driven, rather than items generated by a monitor) to request a ping
  // should not have a nonzero m_int_err_cyc: generating ping signal integrity errors is not yet
  // supported by the driver.
  extern constraint ping_cannot_cause_int_err_c;

  `uvm_object_utils_begin(alert_seq_item)
    `uvm_field_enum(alert_trans_type_e, m_trans_type, UVM_DEFAULT)
    `uvm_field_int (m_int_err_cyc,     UVM_DEFAULT)
    `uvm_field_int (m_ping_delay,      UVM_DEFAULT)
    `uvm_field_int (m_ack_delay,       UVM_DEFAULT)
    `uvm_field_int (m_ack_stable,      UVM_DEFAULT)
    `uvm_field_int (m_alert_delay,     UVM_DEFAULT)
    `uvm_field_enum(alert_handshake_e, m_alert_handshake_sta, UVM_DEFAULT)
  `uvm_object_utils_end
endclass

function alert_seq_item::new (string name = "");
  super.new(name);
endfunction

constraint alert_seq_item::delay_c {
  soft m_ack_delay   <= 32;
  soft m_ack_stable  <= 32;
  soft m_alert_delay <= 32;
}

constraint alert_seq_item::ping_or_alert_c {
  m_trans_type inside {AlertPingTrans, AlertSigTrans};
}

constraint alert_seq_item::int_err_cyc_c {
  soft m_int_err_cyc == 0;
  m_int_err_cyc dist {0 :/ 1, 1 :/ 50, [2:10] :/ 50};
}

constraint alert_seq_item::ping_cannot_cause_int_err_c {
  m_trans_type == AlertPingTrans -> m_int_err_cyc == 0;
}
