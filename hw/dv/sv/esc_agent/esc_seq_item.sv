// An item that represents transactions on an escalation interface

class esc_seq_item extends uvm_sequence_item;
  // If this field is nonzero, the driver will cause a signal integrity error of that many cycles
  // when driving this item.
  rand int unsigned m_int_err_cyc;

  // This value is only set by monitors and gives the type of the transaction that has been seen (a
  // ping, an escalation, or a signal integrity failure).
  esc_trans_type_e  m_trans_type;

  // This bit is set on items generated by a monitor that has seen a timeout caused by an
  // alert/escalation sender not responding to a ping.
  //
  // The field is also used in sequence items that are randomised and will be driven. For example,
  // see esc_receiver_base_seq.
  rand bit          m_ping_timeout;

  // An agent acting as an escalation receiver should generate an integrity error if this is true.
  rand bit          m_standalone_int_err;

  // Generated by esc_monitor: this item shows the current stage of the escelation handshake
  esc_handshake_e   m_esc_handshake_sta;

  // The number of cycles that esc_p stayed high
  int unsigned      m_sig_cycle_cnt;

  extern function new (string name = "");

  // Constraints on m_int_err_cyc
  //
  // Normally, we don't want to generate signal integrity errors, so there's a soft constraint that
  // m_int_err_cyc is zero. If this is overridden or disabled, provide a distribution for the length
  // of the signal integrity error.
  extern constraint int_err_cyc_c;

  `uvm_object_utils_begin(esc_seq_item)
    `uvm_field_int (m_int_err_cyc,  UVM_DEFAULT)
    `uvm_field_enum(esc_trans_type_e, m_trans_type, UVM_DEFAULT)
    `uvm_field_int (m_ping_timeout, UVM_DEFAULT)
    `uvm_field_int (m_standalone_int_err, UVM_DEFAULT)
    `uvm_field_enum(esc_handshake_e, m_esc_handshake_sta, UVM_DEFAULT)
    `uvm_field_int (m_sig_cycle_cnt, UVM_DEFAULT)
  `uvm_object_utils_end
endclass : esc_seq_item

function esc_seq_item::new (string name = "");
  super.new(name);
endfunction

constraint esc_seq_item::int_err_cyc_c {
  // Normally we constrain m_int_err_cyc to be zero. But it's a soft constraint, so the call-site
  // that drives the randomisation can override it by adding a hard "m_int_err_cyc != 0" constraint.
  //
  // If the call-site *has* overridden the constraint (but hasn't disabled this whole constraint by
  // name), we want to control the distribution of values. The obvious way to express that would be
  // something like "m_int_err_cyc != 0 -> m_int_err_cyc dist {some_distribution_here};", but that
  // doesn't work in EDA tools that can't solve distributions in parallel with hard constraints.
  //
  // Fortunately, we can cheat! The trick is to use a single distribution statement that gives a
  // nonzero probability to m_int_err_cyc == 0. This allows the usual case (where the value is
  // *constrained* to equal zero), and doesn't affect the special case (because the value is already
  // constrained not to equal zero).
  soft m_int_err_cyc == 0;
  m_int_err_cyc dist {0 := 1, 1 :/ 1, [2:10] :/ 1};
}
