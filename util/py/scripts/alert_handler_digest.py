"""Regenerate alert_handler's Rust bindings and OTP alert digest values.

Regenerates sw/host/opentitanlib/src/otp/alert_handler_regs.rs via bindgen
from the given top's alert_handler.hjson, then recomputes and patches the
OWNER_SW_CFG_ROM_ALERT_DIGEST_* values in otp_ctrl_img_owner_sw_cfg.hjson
to match.

Usage: python3 util/py/scripts/alert_handler_digest.py --top earlgrey
"""

import argparse
import inspect
import hjson
import re
import subprocess as sp
import pathlib
import tempfile


REPO_ROOT = pathlib.Path(__file__).parent.parent.parent.parent.resolve()


def abspath(relpath: str):
    return str(REPO_ROOT / relpath)


parser = argparse.ArgumentParser()
parser.add_argument('-t', '--top', required=True,
                    help='Top name, e.g. "earlgrey" for top_earlgrey.')
args = parser.parse_args()
top = f'top_{args.top}'

# Generate temporary `alert_handler_regs.h` from `alert_handler.hjson`.
alert_handler_regs_h = tempfile.NamedTemporaryFile(prefix='alert_handler_regs',
                                                   suffix='.h')
sp.run([abspath('util/regtool.py'),
        abspath(f'hw/{top}/ip_autogen/alert_handler/data/alert_handler.hjson'),
        '-D',
        '-o',
        alert_handler_regs_h.name],
       check=True)

# Generate `alert_handler_regs.rs` from temporary `alert_handler_regs.h`.
alert_handler_regs_rs = abspath('sw/host/opentitanlib/src/otp/alert_handler_regs.rs')
sp.run(['bindgen',
        alert_handler_regs_h.name,
        '-o',
        alert_handler_regs_rs],
       check=True)

# Prepend license header, which `bindgen` removed, to `alert_handler_regs.rs`.
with open(alert_handler_regs_rs, 'r') as f:
    data = f.read()
with open(alert_handler_regs_rs, 'w') as f:
    header = f'''// Copyright lowRISC contributors (OpenTitan project).
                // Licensed under the Apache License, Version 2.0, see LICENSE for details.
                // SPDX-License-Identifier: Apache-2.0

                // This file is automatically generated by:
                // python3 util/py/scripts/alert_handler_digest.py --top {args.top}
             '''
    header = inspect.cleandoc(header) + '\n\n'
    f.write(header + data)

# Compute new alert digest values for `otp_ctrl_img_owner_sw_cfg.hjson`.
otp_ctrl_img_owner_sw_cfg = abspath(
    f'hw/{top}/data/otp/otp_ctrl_img_owner_sw_cfg.hjson')
proc = sp.run(['bazel',
               'run',
               '//sw/host/opentitantool',
               '--',
               '--rcfile=""',
               'otp',
               'alert-digest',
               otp_ctrl_img_owner_sw_cfg],
              capture_output=True, check=True)
data = hjson.loads(proc.stdout.decode())
items = data['partitions'][0]['items']
cfg = {i['name']: hex(i['value']) for i in items}

# Replace alert digest values in `otp_ctrl_img_owner_sw_cfg.hjson` while
# keeping the rest of the file intact.
with open(otp_ctrl_img_owner_sw_cfg, 'r') as f:
    raw_file = f.read()
for name, value in cfg.items():
    name_idx = raw_file.find(name)
    trailer = re.sub(r'value:\s*"?0x[a-fA-F0-9]+"?',
                     f'value: "{value}"',
                     raw_file[name_idx:],
                     count=1)
    raw_file = raw_file[:name_idx] + trailer
with open(otp_ctrl_img_owner_sw_cfg, 'w') as f:
    f.write(raw_file)

# Format the bindgen-generated `alert_handler_regs.rs` to match repo style.
sp.run(['bazel', 'run', '//quality:format_Rust_with_rustfmt'], check=True)
