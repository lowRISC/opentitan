r"""Top Module Documentation Generator
"""
from tabulate import tabulate
from mako.template import Template
from pathlib import Path

from .intermodule import im_netname
from .lib import find_module, find_modules

TABLE_HEADER = '''<!--
DO NOT EDIT THIS FILE DIRECTLY.
It has been generated with the following command:
{}
-->
'''


def set_md_table_font_size(row, size):
    """Wrap each row element with HTML tags and specify font size"""
    for k, elem in enumerate(row):
        row[k] = '<p style="font-size:' + str(size) + '">' + elem + '</p>'
    return row


def create_pinout_table(top, c_helper, target):
    """Create the pinout table for a specific target and extract some stats"""
    header = [
        "Pad Name", "Type", "Bank", "Connection", "Special Function",
        "Pinmux Insel Constant / Muxed Output Index", "Description"
    ]
    table_rows = [set_md_table_font_size(header, "smaller")]
    colalign = ("center", ) * len(header)

    # Pad stats
    stats = {}
    stats['muxed'] = 0
    stats['direct'] = 0
    stats['manual'] = 0

    # get all pads for this target
    pads = top['pinout']['pads'] + target['pinout']['add_pads']
    remove_ports = target['pinout']['remove_ports']
    remove_pads = target['pinout']['remove_pads']
    special_signals = target['pinmux']['special_signals']

    # map pad names to special function signals
    special_pads = {}
    for sig in special_signals:
        special_pads.update(
            {sig['pad']: {
                'name': sig['name'],
                'desc': sig['desc']
            }})

    i = 2  # insel enum starts at 2
    j = 0  # mio_out enum starts at 0
    for pad in pads:
        # get the corresponding insel constant and MIO output index
        if pad['connection'] == 'muxed':
            name, _, _ = c_helper.pinmux_insel.constants[i]
            insel = name.as_c_enum()
            name, _, _ = c_helper.pinmux_mio_out.constants[j]
            mio_out = name.as_c_enum()
            i += 1
            j += 1
        else:
            insel = "-"
            mio_out = "-"
        # check whether this pad/port needs to be dropped
        if pad['name'] in remove_ports:
            continue
        if pad['name'] in remove_pads:
            continue
        # gather some stats
        stats[pad['connection']] += 1
        # annotate special functions
        if pad['name'] in special_pads:
            special_func = special_pads[pad['name']]['name']
            desc = pad['desc'] + " / " + special_pads[pad['name']]['desc']
        else:
            special_func = "-"
            desc = pad['desc']
        row = [
            pad['name'], pad['type'], pad['bank'], pad['connection'],
            special_func, insel + ' / ' + mio_out, desc
        ]
        table_rows.append(set_md_table_font_size(row, "smaller"))

    ret_str = tabulate(table_rows,
                       headers="firstrow",
                       tablefmt="pipe",
                       colalign=colalign)

    return ret_str, stats


def create_pinmux_table(top, c_helper):
    """Create the pinmux connectivity table"""
    header = [
        "Module / Signal", "Connection", "Pad",
        "Pinmux Outsel Constant / Peripheral Input Index", "Description"
    ]
    table_rows = [set_md_table_font_size(header, "smaller")]
    colalign = ("center", ) * len(header)

    i = 3  # outsel enum starts at 3
    j = 0  # periph_input enum starts at 0
    for sig in top['pinmux']['ios']:
        port = sig['name']
        if sig['width'] > 1:
            port += '[' + str(sig['idx']) + ']'
        pad = sig['pad'] if sig['pad'] else '-'
        # get the corresponding insel constant
        if sig['connection'] == 'muxed' and sig['type'] in ['inout', 'output']:
            name, _, _ = c_helper.pinmux_outsel.constants[i]
            outsel = name.as_c_enum()
            i += 1
        else:
            outsel = "-"
        # get the corresponding peripheral input index
        if sig['connection'] == 'muxed' and sig['type'] in ['inout', 'input']:
            name, _, _ = c_helper.pinmux_peripheral_in.constants[j]
            periph_in = name.as_c_enum()
            j += 1
        else:
            periph_in = "-"
        row = [
            port, sig['connection'], pad, outsel + " / " + periph_in,
            sig['desc']
        ]
        table_rows.append(set_md_table_font_size(row, "smaller"))

    return tabulate(table_rows,
                    headers="firstrow",
                    tablefmt="pipe",
                    colalign=colalign)


def gen_pinmux_docs(top, c_helper, out_path):
    """Generate pinmux/pinout summary table and linked pinout subtables for each target.

    All files are placed in the top's ip_autogen/pinmux/doc directory.
    e.g.
    <out_path>
    └── ip_autogen
        └── pinmux
            └── doc
                ├── pinout_asic.md    # subtable
                ├── pinout_cw340.md   # subtable
                └── targets.md        # Summary table
    """

    # 'out_path' is the top-level directory for a generated top (e.g. hw/top_earlgrey)
    pinmux_top_doc_path = out_path / 'ip_autogen' / 'pinmux' / 'doc'
    pinmux_top_doc_path.mkdir(parents=True, exist_ok=True)

    gencmd = ("util/topgen.py -t hw/top_{topname}/data/top_{topname}.hjson "
              "-o hw/top_{topname}/".format(topname=top['name']))

    header = [
        "Target Name", "#IO Banks", "#Muxed Pads", "#Direct Pads",
        "#Manual Pads", "#Total Pads", "Pinout / Pinmux Tables"
    ]
    table_rows = [header]
    colalign = ("center", ) * len(header)

    # Create subtables for each pinout target, plus a row in the summary table
    for target in top['targets']:
        name = target['name']
        pinout_name = f"pinout_{name}.md"
        table_str, stats = create_pinout_table(top, c_helper, target)

        # create file with pinout+pinmux subtable for this target
        pinout_table = (
            f'# "{name.upper()}" Target : Pinout and Pinmux Connectivity\n')
        pinout_table += TABLE_HEADER.format(gencmd)
        pinout_table += '## Pinout Table\n\n'
        pinout_table += table_str + '\n'
        pinout_table += '## Pinmux Connectivity\n\n'
        pinout_table += create_pinmux_table(top, c_helper)
        pinout_table += "\n"
        pinout_table_path = pinmux_top_doc_path / pinout_name
        pinout_table_path.write_text(pinout_table)

        # create summary table row
        row = [
            name.upper(),  # target name
            len(top['pinout']['banks']),  # io banks
            stats['muxed'],  # muxed pads
            stats['direct'],  # direct pads
            stats['manual'],  # manual pads
            stats['muxed'] + stats['direct'] + stats['manual'],  # total pads
            # subtable, in same dir as the summary table
            f"[Pinout Table](./{pinout_name})"
        ]
        table_rows.append(row)

    # Now create the summary table
    summary_table = f'# {top["name"].capitalize()} Pinout and Pinmux Connectivity Tables\n'
    summary_table += TABLE_HEADER.format(gencmd)
    summary_table += tabulate(table_rows,
                              headers="firstrow",
                              tablefmt="pipe",
                              colalign=colalign)
    summary_table += "\n"
    summary_table_path = pinmux_top_doc_path / "targets.md"
    summary_table_path.write_text(summary_table)


def gen_memory_map_docs(top, c_helper, out_path):
    """Generate memory map documentation for all address spaces.

    Creates a markdown file showing the memory layout for all address spaces
    defined in the top configuration.
    """
    doc_path = out_path / 'doc'
    doc_path.mkdir(parents=True, exist_ok=True)

    gencmd = ("util/topgen.py -t hw/top_{topname}/data/top_{topname}.hjson "
              "-o hw/top_{topname}/".format(topname=top["name"]))

    template_path = Path(__file__).parent / "templates" / "memory_map.md.tpl"
    template = Template(filename=str(template_path))

    memory_map_content = template.render(
        top=top,
        helper=c_helper,
        gencmd=gencmd
    )

    memory_map_path = doc_path / "memory_map.md"
    memory_map_path.write_text(memory_map_content)


def _ibex_input_source(top, ibex, sig_name):
    """Describe what drives the inter-module input `sig_name` of the Ibex
    wrapper `ibex` in the top."""
    sig = next(s for s in ibex["inter_signal_list"] if s["name"] == sig_name)
    if "top_signame" not in sig:
        return "Not connected, tied to `{}`".format(im_netname(sig))

    endpoint = "{}.{}".format(ibex["name"], sig_name)
    inter_module = top["inter_module"]
    for req, rcvs in inter_module["connect"].items():
        if endpoint in rcvs:
            # A non-negative index selects one element of an array req.
            index = sig.get("index", -1)
            if index != -1 and "[" not in req:
                return "`{}[{}]`".format(req, index)
            return "`{}`".format(req)
    if endpoint in inter_module.get("external", {}):
        return "Top-level port `{}`".format(
            inter_module["external"][endpoint])
    return "`{}`, assigned in the top-level template".format(
        sig["top_signame"])


def _plic_irq_rows(top, c_helper, plic_name):
    """List the interrupts of one PLIC, one row per interrupt ID.

    The IDs and C names come from the same enum as `top_<name>.h`, so the
    loop below must visit the interrupts in the order the C helper does.
    """
    default_plic = top.get("default_plic", None)
    intrs = []
    for intr in top["interrupt"]:
        if intr.get("plic", default_plic) != plic_name:
            continue
        module = intr["module_name"]
        short_name = intr["name"]
        if short_name.startswith(module + "_"):
            short_name = short_name[len(module) + 1:]
        if intr["incoming"]:
            module += " (incoming)"
        intr_type = intr.get("intr_type", "")
        intr_type = getattr(intr_type, "name", str(intr_type).split(".")[-1])
        width = int(intr.get("width", 1))
        if width == 1:
            intrs.append([module, short_name, intr_type])
        else:
            for i in range(width):
                intrs.append(
                    [module, "{}[{}]".format(short_name, i), intr_type])

    # Skip the "none" constant at ID 0.
    constants = c_helper.plic_interrupts[plic_name].constants[1:]
    assert len(constants) == len(intrs)
    return [[str(value), "`{}`".format(name.as_c_enum())] + intr
            for (name, value, _), intr in zip(constants, intrs)]


def gen_interrupts_docs(top, c_helper, out_path):
    """Generate the interrupt documentation of the top.

    Lists what drives each slot of the Ibex vector table and every PLIC
    interrupt ID.
    """
    ibex = find_module(top["module"], "rv_core_ibex")
    if ibex is None:
        return

    params = {p["name"]: p.get("default") for p in ibex.get("param_list", [])}
    secure_ibex = str(params.get("SecureIbex", "0")).strip() in ("1", "1'b1")

    slot_rows = [
        ["0", "`0x00`", "Exception code", "", "Synchronous exceptions"],
        ["3", "`0x0C`", "`0x80000003`", "`irq_software_i`",
         _ibex_input_source(top, ibex, "irq_software")],
        ["7", "`0x1C`", "`0x80000007`", "`irq_timer_i`",
         _ibex_input_source(top, ibex, "irq_timer")],
        ["11", "`0x2C`", "`0x8000000B`", "`irq_external_i`",
         _ibex_input_source(top, ibex, "irq_external")],
        ["16-30", "`0x40`-`0x78`", "`0x80000010`-`0x8000001E`",
         "`irq_fast_i`", "Tied to 0 in `rv_core_ibex`"],
        ["31", "`0x7C`", "`0x8000001F`", "`irq_nm_i`",
         "`NMI_STATE` of `{}`".format(ibex["name"])],
    ]
    if secure_ibex:
        slot_rows.append(["31", "`0x7C`", "`0xFFFFFFE0`", "",
                          "Ibex bus integrity error"])
    slot_table = tabulate(
        slot_rows,
        headers=["Slot", "Offset", "`mcause`", "Ibex input", "Source"],
        tablefmt="github", disable_numparse=True)

    nmi_table = tabulate(
        [["`NMI_STATE.ALERT`", _ibex_input_source(top, ibex, "esc_tx")],
         ["`NMI_STATE.WDOG`", _ibex_input_source(top, ibex, "nmi_wdog")]],
        headers=["Field", "Source"],
        tablefmt="github", disable_numparse=True)

    plic_tables = []
    for plic in find_modules(top["module"], "rv_plic"):
        enum_name = c_helper.plic_interrupts[plic["name"]].name
        plic_tables.append({
            "name": plic["name"],
            "enum": enum_name.as_c_type(),
            "table": tabulate(
                _plic_irq_rows(top, c_helper, plic["name"]),
                headers=["ID", "C name", "Module", "Interrupt", "Type"],
                tablefmt="github", disable_numparse=True),
        })

    registers_link = None
    if ibex.get("attr") == "ipgen":
        registers_link = "../ip_autogen/{}/doc/registers.md".format(
            ibex["type"])

    gencmd = ("util/topgen.py -t hw/top_{topname}/data/top_{topname}.hjson "
              "-o hw/top_{topname}/".format(topname=top["name"]))

    template_path = Path(__file__).parent / "templates" / "interrupts.md.tpl"
    template = Template(filename=str(template_path))
    content = template.render(
        top=top,
        ibex_name=ibex["name"],
        secure_ibex=secure_ibex,
        slot_table=slot_table,
        nmi_table=nmi_table,
        plic_tables=plic_tables,
        registers_link=registers_link,
        gencmd=gencmd,
    )

    doc_path = out_path / "doc"
    doc_path.mkdir(parents=True, exist_ok=True)
    (doc_path / "interrupts.md").write_text(content)


def gen_top_docs(top, c_helper, out_path):
    gen_memory_map_docs(top, c_helper, out_path)
    gen_interrupts_docs(top, c_helper, out_path)

    if find_module(top['module'], 'pinmux'):
        # create pinout / pinmux specific tables for all targets
        gen_pinmux_docs(top, c_helper, out_path)
