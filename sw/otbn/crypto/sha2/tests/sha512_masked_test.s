.section .text.start
main:
  /* Set the number of message chunks (in blocks of 1024 bits) */
  li      x30, 2

  /* Load pointers to Share 0 and Share 1 of the padded message */
  la      x10, msg_s0
  la      x11, msg_s1

  /* Run the SHA-512 masked process */
  jal     x1, sha512_masked

  /* Load the final state into registers for the test environment to check */
  la      x2, state_s0
  li      x4, 0
  bn.lid  x4, 0(x2)
  la      x2, state_s1
  li      x4, 1
  bn.lid  x4, 0(x2)
  /* Unmask efgh into w2 */
  bn.xor  w2, w0, w1

  la      x2, state_s0
  li      x4, 0
  bn.lid  x4, 32(x2)
  la      x2, state_s1
  li      x4, 1
  bn.lid  x4, 32(x2)
  /* Unmask abcd into w3 */
  bn.xor  w3, w0, w1

  ecall

.data

