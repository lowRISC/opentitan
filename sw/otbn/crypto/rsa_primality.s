# Primality tests. The routines in this file are structured around `modexp` and
# make use of pre-defined memory location in `run_rsa_mem`.

.text
.globl gen_prime_candidate
.globl fermat_test
.globl miller_rabin_test
.globl rsa_check_modulus

/**
 * Hardened boolean values.
 *
 * Should match the values in `hardened_asm.h`.
 */
.equ HARDENED_BOOL_TRUE, 0x739
.equ HARDENED_BOOL_FALSE, 0x1d4

/**
 * Perform the Fermat primality test.
 *
 * This function calculates w^(p-1) mod p for some random witness w and a prime
 * candidate. If w is not divisble by p and p is prime, then w^(p-1) mod p = 1.
 * The only composite numbers that pass this test are pseudoprimes which need
 * be sieved out by an additional primality test (see miller_rabin_test).
 *
 * The test consists of a single exponentiation (i.e., one invocation of
 * `modexp`).
 *
 * @param[in] DMEM[rsa_n]: candidate prime p to check, with p = 3 mod 4.
 * @param[in]     x30: N, number of limbs of the prime
 * @param[in]     w31: all-zero
 * @param[out]     x2: result, 1 if w^(p-1) mod p else 0.
 *
 * This routine is constant-time.
 *
 * Clobbered registers: x2 to x26, x31
 *                      w2, w3, w4 to w[4+N-1], w24 to w30
 * Clobbered flag groups: FG0, FG1
 */
fermat_test:
  # Load the Montgomery constants.
  la  x16, rsa_n
  la  x17, RR
  jal x1, modload

  # Constant wide register pointers.
  li x8, 2
  li x9, 3

  # Mask the prime candidate and move it to DMEM.
  # dmem[rsa_d0] <= p ^ m
  # dmem[rsa_d1] <= m
  la x12, rsa_n
  la x13, rsa_d0
  la x14, rsa_d1
  loop x30, 6
    bn.lid  x8, 0(x12++)
    bn.wsrr w3, URND
    bn.xor  w2, w2, w3
    bn.sid  x8, 0(x13++)
    bn.xor  w31, w31, w31 # dummy instruction
    bn.sid  x9, 0(x14++)

  # Since p is odd p-1 must be even, hence to have d0 XOR d1 = p-1, the first
  # bit of the share d0 must be flipped.
  la      x12, rsa_d0
  bn.addi w3, w31, 1
  bn.lid  x8, 0(x12)
  bn.xor  w2, w2, w3
  bn.sid  x8, 0(x12)

  # Generate a witness w as the exponentation base point.
  # dmem[r0] <= w
  la  x16, r0
  la  x17, rsa_n
  jal x1, gen_witness

  # Calculate w^(p-1) mod p with message blinding is disabled.
  # dmem[r0] <= w^(p-1) mod p
  li x29, 0
  jal x1, modexp

  # Check whether w^(p-1) mod p == 1.
  la x16, r0
  jal x1, is_1

  ret

/**
 * Perform the Miller-Rabin primality test.
 *
 * Repeatedly calculate w^((p-1)/2) mod p for a random witness w and check
 * whether it equals 1 or p-1. This is a simplified variant of the algorithm of
 * Section A.1.3 of FIPS 186-5 for candidates primes of the form p mod 4 = 3 as
 * they are generated by `gen_prime_candidate`. The routine unfolds as follows:
 *
 *   x = (p-1)/2
 *   c = 0
 *   for i in num_iterations do
 *     Choose a random witness w, 1 < w < p-1
 *     y = w^x mod p
 *     if y = 1 or y = p-1 then
 *       c = c + 1
 *     endif
 *   endfor
 *   if c != num_iterations then
 *     return COMPOSITE
 *   endif
 *   return PROBABLY PRIME
 *
 * This routine is constant-time with respect to p, if p is prime.
 *
 * @param[out] x2: result, 1 if p is probably prime else 0.
 * @param[out] x28: c, number of passed Miller-Rabin rounds.
 *
 * Clobbered registers: x2 to x26, x31
 *                      w2, w3, w4 to w[4+N-1], w24 to w30
 * Clobbered flag groups: FG0, FG1
 */
miller_rabin_test:
  # Reset the Miller-Rabin round counter.
  addi x28, x0, 0

  # Load the Montgomery constants.
  la  x16, rsa_n
  la  x17, RR
  jal x1, modload

  # Constant wide register pointers.
  li x8, 2
  li x9, 3

  # Mask the prime candidate and move it to DMEM[d0], DMEM[d1].
  # dmem[rsa_d0] <= p ^ m
  # dmem[rsa_d1] <= m
  la x12, rsa_n
  la x13, rsa_d0
  la x14, rsa_d1
  loop x30, 6
    bn.lid  x8, 0(x12++)
    bn.wsrr w3, URND
    bn.xor w2, w2, w3
    bn.sid x8, 0(x13++)
    bn.xor w31, w31, w31 # dummy instruction
    bn.sid x9, 0(x14++)

  # Since p is odd p-1 must be even, hence to have d0 XOR d1 = p-1, the first
  # bit of the share d0 must be flipped.
  # dmem[rsa_d0] <= (p-1) ^ m
  # dmem[rsa_d1] <= m
  la      x12, rsa_d0
  bn.addi w3, w31, 1
  bn.lid  x8, 0(x12)
  bn.xor  w2, w2, w3
  bn.sid  x8, 0(x12)

  # Calculate (p-1)/2 by shifting the shares one position to the right.
  # dmem[rsa_d0] <= ((p-1) ^ m) >> 1
  # dmem[rsa_d1] <= m >> 1
  la   x13, rsa_d0
  la   x14, rsa_d1
  addi x31, x30, -1
  loop x31, 9
    bn.lid  x8, 0(x13)
    bn.lid  x9, 32(x13)
    bn.rshi w2, w3, w2 >> 1
    bn.sid  x8, 0(x13++)
    bn.xor  w31, w31, w31 # dummy instruction
    bn.lid  x8, 0(x14)
    bn.lid  x9, 32(x14)
    bn.rshi w2, w3, w2 >> 1
    bn.sid  x8, 0(x14++)

  # Insert a random bit at the MSB of the shifted last word.
  bn.wsrr w3, URND
  bn.rshi w3, w3, w31 >> 1

  bn.lid  x8, 0(x13)
  bn.rshi w2, w31, w2 >> 1
  bn.or   w2, w2, w3
  bn.sid  x8, 0(x13++)
  bn.xor  w31, w31, w31 # dummy instruction
  bn.lid  x8, 0(x14)
  bn.rshi w2, w31, w2 >> 1
  bn.or   w2, w2, w3
  bn.sid  x8,  0(x14++)

  # Fix the number of iterations to 4 in accordance with Table B.1 of
  # FIPS 186-5 to reach an error probability of less than 2^-100 for
  # RSA-{2048,3072,4096}.
  loopi 4, 32
    # Generate a witness w as the exponentation base point.
    # dmem[r0] <= w
    la  x16, r0
    la  x17, rsa_n
    jal x1, gen_witness

    # Calculate w^(p-1) mod p with message blinding disabled.
    # dmem[r0] <= w^(p-1) mod p
    li x29, 0
    jal x1, modexp

    # Check whether w^(p-1) mod p = 1.
    # x2 <= 1 if w^(p-1) mod p = 1 else x2 <= 0.
    la x16, r0
    jal x1, is_1

    addi x3, x2, 0

    # Check whether w^(p-1) mod p = p-1.
    # x2 <= 1 if w^(p-1) mod p = p-1 else x2 <= 0.
    la x16, r0
    la x17, rsa_n
    jal x1, is_pminus1

    # At this point, if neither w^(p-1) mod p = 1 or w^(p-1) mod p = p-1, then
    # p must be a composite number.
    or x2, x2, x3

    # Remask the shared exponents.
    li   x8, 2
    la   x13, rsa_d0
    la   x14, rsa_d1
    loop x30, 8
      bn.lid  x8, 0(x13)
      bn.wsrr w3, URND
      bn.xor  w2, w2, w3
      bn.sid  x8, 0(x13++)
      bn.xor  w31, w31, w31 # dummy instruction
      bn.lid  x8, 0(x14)
      bn.xor  w2, w2, w3
      bn.sid  x8, 0(x14++)
    # Increment the iteration counter. To be written to DMEM after the
    # Miller-Rabin test to make sure all rounds have been executed.
    add x28, x28, x2

  # p is probably prime iff all rounds passed.
  # x2 <= 1 if x28 = 4 else x2 <= 0.
  li  x2, 0
  li  x3, 4
  bne x28, x3, _miller_rabin_epilogue
  li  x2, 1

_miller_rabin_epilogue:
  ret

/**
 * Generate a n-limbed candidate prime.
 *
 * Fixes the lowest 3 bits to 1 and the highest 2 bits to 1, so the number is
 * always equivalent to 7 mod 8 and is always >= 2^(256*n - 1) * 1.5.  This
 * implies that the prime candidate is always in range, i.e. it is greater than
 * sqrt(2) * (2^(256*n - 1)), because sqrt(2) < 1.5. All other bits are fully
 * random. This follows FIPS 186-5 section A.1.3, which allows generating prime
 * candidates with a specific value mod 8 and allows the highest 2 bits to be
 * set arbitrarily.
 *
 * Flags: Flags have no meaning beyond the scope of this subroutine.
 *
 * @param[in]  x16: dptr_result, address of the result buffer in DMEM
 * @param[in]  x30: n, number of 256-bit limbs for the result
 * @param[in]  w31: all-zero
 * @param[out] dmem[x16..x16+(n*32)]: random candidate prime
 *
 * clobbered registers: x2, x3, w20, w21
 * clobbered flag groups: FG0
 */
gen_prime_candidate:
  # Constant wide register index.
  li x20, 20

  # Generate random 256-bit limbs.
  # dmem[x16..x16+(n*32)] <= RND(n*32) ^ URND(n*32)
  addi x2, x16, 0
  loop x30, 4
    bn.wsrr w20, RND      # w20 <= RND()
    bn.wsrr w21, URND     # w21 <= URND()
    bn.xor  w20, w20, w21 # w20 <= w20 ^ w21
    bn.sid  x20, 0(x2++)  # dmem[x2] <= w20

  # Fix the lowest 3 bits to 1 so the number is always 7 mod 8.
  # dmem[x16] <= dmem[x16] | 7
  bn.lid  x20, 0(x16)
  bn.addi w21, w31, 7
  bn.or   w20, w20, w21
  bn.sid  x20, 0(x16)

  # Get a pointer to the last limb.
  # x2 <= x16 + ((n-1) << 5) = x16 + (n-1)*32
  addi x31, x30, -1
  slli x3, x31, 5
  add  x2, x16, x3

  # Fix the highest 2 bits to 1.
  # dmem[x2] <= dmem[x2] | (3 << 6) << 248 = dmem[x2] | 3 << 254
  bn.lid  x20, 0(x2)
  bn.addi w21, w31, 192
  bn.or   w20, w20, w21 << 248
  bn.sid  x20, 0(x2)

  ret

/**
 * Generate a new random witness for the Fermat and Miller-Rabin tests.
 *
 * The witness w is guaranteed to been in the interval 1 < w < b-1.
 *
 * @param[in] x16, dptr_w, DMEM location to result witness w
 * @param[in] x17, dptr_b, DMEM pointer to the bound b
 * @param[in] x30, n, number of limbs
 */
gen_witness:
  li x8, 23
  li x9, 24

  # dmem[dptr_w:dptr_w+n*32] <= RND(n*32) ^ URND(n*32) = w
  addi x10, x16, 0
  loop x30, 4
    bn.wsrr w22, URND     # w22  <= URND()
    bn.wsrr w23, RND      # w23  <= RND()
    bn.xor  w23, w22, w23 # w23  <= w22 ^ w23
    bn.sid  x8, 0(x10++)  # b[i] <= w23

  # Clear flags and compute the constant 1.
  # w22   <= 1
  # FG0.C <= 0
  # FG1.C <= 0
  bn.addi w22, w31, 1
  bn.add  w31, w31, w31, FG1

  # Check that w < b - 1. Computes b - 1 limb by limb using the borrow bit in
  # FG1 and compares it against w using the borrow bit in FG0.
  # FG0.C <= w <? b - 1
  addi x10, x16, 0
  addi x11, x17, 0
  loop x30, 5
    bn.lid  x8, 0(x10++)       # w23   <= w[i]
    bn.lid  x9, 0(x11++)       # w24   <= b[i]
    bn.subb w24, w24, w22, FG1 # w24   <= (b-1)[i]
    bn.cmpb w23, w24           # FG0.C <= w[i] - (b-1)[i] - FG0.C
    bn.mov  w22, w31           # w22   <= 0

  # Extract FG0.C into a small register and jump back to the start if it is 0.
  # x2 <= CSRs[FG0][0] = FG0.C
  csrrs x2, FG0, x0
  andi  x2, x2, 1
  beq   x2, x0, gen_witness

  # Clear flags and compute the constant 1.
  # w21   <= 1
  # FG0.C <= 0
  bn.addi w22, w31, 1

  # Check that 1 < b.
  # FG0.C <= 1 <? b
  addi x10, x16, 0
  loop x30, 3
    bn.lid  x8, 0(x10++) # w23   <= b[i]
    bn.cmpb w22, w23     # FG0.C <= (i = 0 ? 1 : 0) - b[i] - FG0.C
    bn.mov  w22, w31     # w22   <= 0

  # Extract FG0.C into a small register and retry if it is 0.
  # x2 <= CSRs[FG0][0] = FG0.C
  csrrs x2, FG0, x0
  andi  x2, x2, 1
  beq   x2, x0, gen_witness

  ret

/**
 * Check whether the multi-word value x is equal to 1.
 *
 * Returns 1 in x2 if x == 1 else 0.
 *
 * @param[in]  x16: dptr_x, pointer to input buffer x in dmem
 * @param[in]  x30: n, number of limbs
 * @param[in]  w31: all-zero
 * @param[out]  x2: result, 1 if x == 1 else 0
 *
 * Clobbered Registers: x8, x9, x31, w2, w24, w25
 * Clobbered Flag Groups: FG0
 */
is_1:
  li x8, 2
  li x9, 3
  addi x10, x16, 0

  # w24 <= 2^256-1
  # w25 <= 2^256-1
  bn.sub   w24, w24, w24
  bn.not   w24, w24
  bn.mov   w25, w24

  bn.addi w4, w31, 1

  # Check all the words for equality.
  loop x30, 6
    bn.lid x8, 0(x10++)
    # For the lowest word use w4 for the comparison otherwise w3.
    # FG0.Z <= 1 if w25 = 0 else 0.
    bn.cmp w25, w31, FG0
    bn.sel w3, w31, w4, FG0.Z
    bn.xor w25, w25, w25
    # Compare for equality.
    # FG0.Z <= 1 if w2 = w3 else 0.
    bn.cmp w2, w3, FG0
    bn.sel w24, w24, w31, FG0.Z

  # Compare the result of the check to the "check passed" all-1s value.
  # FG0.Z <= (w24 == 2^256-1)
  bn.not w25, w31
  bn.cmp w25, w24

  # Get the FG0.Z flag into a register.
  # x2 <= CSRs[FG0] & 8 = FG0.Z << 3
  csrrs x2, FG0, x0
  andi  x2, x2, 8
  srli  x2, x2, 3

  ret

/**
 * Check whether the x is equal to the modulus p-1.
 *
 * Returns 1 in x2 if x == 1 else 0.
 * Note that p-1 is assumed to an even number.
 *
 * @param[in]  x16: dptr_x, pointer to input buffer x in dmem
 * @param[in]  x17: dptr_p, modulus p
 * @param[in]  x30: n, number of limbs
 * @param[out]  x2: result, 1 if x == (p-1) else 0
 *
 * Clobbered Registers: x8, x9, x10, x11, w2, w3, w24, w25
 * Clobbered Flag Groups: FG00
 */
is_pminus1:
  # Prepare DMEM and wide register pointers.
  li x8, 2
  li x9, 3
  addi x10, x16, 0
  addi x11, x17, 0

  # w24 <= 2^256-1
  # w25 <= 2^256-1
  bn.sub   w24, w24, w24
  bn.not   w24, w24
  bn.mov   w25, w24

  # Subtract 1 from the lowest word of p, which is results in p-1 since p is an
  # odd number.
  bn.lid  x9, 0(x11)
  bn.subi w4, w3, 1

  # Check all the words for equality.
  loop x30, 7
    bn.lid x8, 0(x10++)
    bn.lid x9, 0(x11++)
    # For the lowest word use w4 for the comparison otherwise w3.
    # FG0.Z <= 1 if w25 = 0 else 0.
    bn.cmp w25, w31, FG0
    bn.sel w3, w3, w4, FG0.Z
    bn.xor w25, w25, w25
    # Compare for equality.
    # FG0.Z <= 1 if w2 = w3 else 0.
    bn.cmp w2, w3, FG0
    bn.sel w24, w24, w31, FG0.Z

  # Compare the result of the check to the "check passed" all-1s value.
  # FG0.Z <= (w24 == 2^256-1)
  bn.not w25, w31
  bn.cmp w25, w24

  # Get the FG0.Z flag into a register.
  # x2 <= CSRs[FG0] & 8 = FG0.Z << 3
  csrrs x2, FG0, x0
  andi  x2, x2, 8
  srli  x2, x2, 3

  ret

/**
 * Check that an RSA modulus is composite and not a power of a prime.
 *
 * Implements the enhanced Miller-Rabin test of FIPS 186-5, Appendix B.3.2, as
 * required for RSA public-key validation by NIST SP 800-89, Section 5.3.3. The
 * modulus is accepted only if the test returns PROVABLY COMPOSITE AND NOT A
 * POWER OF A PRIME. Both PROBABLY PRIME and PROVABLY COMPOSITE WITH FACTOR are
 * rejected; for a valid modulus n = p*q the latter only happens if a random
 * witness shares a factor with n, which has negligible probability.
 *
 *   a = largest integer such that 2^a divides n-1
 *   m = (n-1) / 2^a
 *   for i in 1..4 do
 *     Choose a random witness b, 1 < b < n-1
 *     if gcd(b, n) != 1 then
 *       return REJECT
 *     z = b^m mod n
 *     if z = 1 or z = n-1 then
 *       continue
 *     for j in 1..a do
 *       x = z
 *       z = x^2 mod n
 *       if z = 1 then
 *         goto final
 *       if j < a and z = n-1 then
 *         continue with the next witness
 *     endfor
 *     x = z
 *   final:
 *     if gcd(x-1, n) != 1 then
 *       return REJECT
 *     return ACCEPT
 *   endfor
 *   return REJECT
 *
 * For a valid RSA modulus the first witness almost always yields ACCEPT, so the
 * cost is dominated by a single full-length exponentiation. Rejected inputs
 * (e.g. a prime n) run all rounds.
 *
 * The modulus is public, so this routine is not constant time. The
 * exponentiation uses `modexp` with message blinding disabled and the
 * exponent m in rsa_d0 (rsa_d1 = 0).
 *
 * The modulus must have its most significant bit set (n > 2^(256*N-1)), so
 * that the redundant Montgomery representation used by `montmul` stays below
 * 2^(256*N). Callers must check this beforehand.
 *
 * DMEM usage: reads rsa_n; overwrites rsa_d0, rsa_d1, r0, r1, r2, RR and
 * work_buf. Since r1 aliases `mode` and `ok`, the caller must rewrite these
 * afterwards.
 *
 * @param[in]  dmem[rsa_n]: n, odd RSA modulus with N limbs
 * @param[in]  x30: N, number of limbs (N >= 2)
 * @param[in]  w31: all-zero
 * @param[out] x2: HARDENED_BOOL_TRUE if n is composite and not a prime power,
 *                 HARDENED_BOOL_FALSE otherwise
 *
 * Clobbered registers: x2 to x29, x31, w0 to w30
 * Clobbered flag groups: FG0, FG1
 */
rsa_check_modulus:
  # Compute the Montgomery constants for n.
  # w1        <= m0'
  # dmem[RR]  <= R^2 mod n
  # x31       <= N - 1
  la  x16, rsa_n
  la  x17, RR
  jal x1, modload

  # Copy n to rsa_d0 and clear rsa_d1.
  # dmem[rsa_d0] <= n
  # dmem[rsa_d1] <= 0
  li   x8, 2
  li   x9, 31
  la   x12, rsa_n
  la   x13, rsa_d0
  la   x14, rsa_d1
  loop x30, 3
    bn.lid  x8, 0(x12++)
    bn.sid  x8, 0(x13++)
    bn.sid  x9, 0(x14++)

  # n is odd, so n-1 only clears the lowest bit.
  # dmem[rsa_d0] <= n-1
  la      x13, rsa_d0
  bn.lid  x8, 0(x13)
  bn.subi w2, w2, 1
  bn.sid  x8, 0(x13)

  # Shift rsa_d0 right until it is odd. Since n-1 > 0 this terminates.
  # x24          <= a
  # dmem[rsa_d0] <= m = (n-1) >> a
  li x24, 0
  li x9, 3
_rsa_check_modulus_shift:
  la   x13, rsa_d0
  lw   x2, 0(x13)
  andi x2, x2, 1
  bne  x2, x0, _rsa_check_modulus_shift_done
  loop x31, 4
    bn.lid  x8, 0(x13)
    bn.lid  x9, 32(x13)
    bn.rshi w2, w3, w2 >> 1
    bn.sid  x8, 0(x13++)
  bn.lid  x8, 0(x13)
  bn.rshi w2, w31, w2 >> 1
  bn.sid  x8, 0(x13)
  addi    x24, x24, 1
  jal     x0, _rsa_check_modulus_shift
_rsa_check_modulus_shift_done:

  # `gcd` and `modexp` clobber most GPRs, so keep the loop state in DMEM. The
  # whole 256-bit word is initialized first since it is moved with bn.lid/sid.
  # dmem[work_buf]   <= number of remaining rounds
  # dmem[work_buf+4] <= a
  la     x2, work_buf
  li     x3, 31
  bn.sid x3, 0(x2)
  li     x3, 4
  sw     x3, 0(x2)
  sw     x24, 4(x2)

_rsa_check_modulus_round:
  # If all rounds are exhausted without a verdict, n is probably prime.
  la   x2, work_buf
  lw   x3, 0(x2)
  beq  x3, x0, _rsa_check_modulus_reject
  addi x3, x3, -1
  sw   x3, 0(x2)

  # Generate a random witness.
  # dmem[r0] <= b, 1 < b < n-1
  la  x16, r0
  la  x17, rsa_n
  jal x1, gen_witness

  # dmem[r1] <= b
  # dmem[r2] <= n
  la  x12, r0
  la  x13, r1
  jal x1, rsa_check_modulus_copy
  la  x12, rsa_n
  la  x13, r2
  jal x1, rsa_check_modulus_copy

  # Reject if b shares a factor with n.
  # dmem[r2] <= gcd(b, n)
  la  x10, r1
  la  x11, r2
  jal x1, gcd
  la  x16, r2
  jal x1, is_1
  beq x2, x0, _rsa_check_modulus_reject

  # Compute z = b^m mod n with message blinding disabled. `modexp` overwrites
  # work_buf but leaves w20 intact, so park the loop state in w20.
  # dmem[r0] <= z
  li     x14, 20
  la     x2, work_buf
  bn.lid x14, 0(x2)
  li     x29, 0
  jal    x1, modexp
  li     x14, 20
  la     x2, work_buf
  bn.sid x14, 0(x2)

  # Continue with the next witness if z = 1 or z = n-1.
  la  x16, r0
  jal x1, is_1
  bne x2, x0, _rsa_check_modulus_round
  la  x16, r0
  la  x17, rsa_n
  jal x1, is_pminus1
  bne x2, x0, _rsa_check_modulus_round

  # Convert z to the Montgomery domain.
  # dmem[r1] <= montmul(z, RR) = z*R mod n
  addi x31, x30, -1
  la   x19, r0
  la   x20, RR
  jal  x1, rsa_check_modulus_montmul
  la   x3, r1
  jal  x1, rsa_check_modulus_store

  # x25 <= a, number of remaining squarings
  la x2, work_buf
  lw x25, 4(x2)

_rsa_check_modulus_square:
  # x31 <= N-1, as required by `montmul` and `montmul_mul1`.
  addi x31, x30, -1

  # dmem[r2] <= x = z
  la  x12, r0
  la  x13, r2
  jal x1, rsa_check_modulus_copy

  # dmem[r1] <= montmul(z*R, z*R) = z^2*R mod n
  la  x19, r1
  la  x20, r1
  jal x1, rsa_check_modulus_montmul
  la  x3, r1
  jal x1, rsa_check_modulus_store

  # Convert back to the normal domain (fully reduced).
  # dmem[r0] <= z = montmul(z^2*R, 1) = x^2 mod n
  li  x8, 4
  li  x9, 3
  li  x10, 4
  li  x11, 2
  la  x16, rsa_n
  la  x19, r1
  la  x21, r0
  jal x1, montmul_mul1

  # If z = 1, then x is a square root of 1 with x != 1.
  la  x16, r0
  jal x1, is_1
  bne x2, x0, _rsa_check_modulus_final

  # After a squarings z = b^(n-1) mod n != 1; use x = z.
  addi x25, x25, -1
  beq  x25, x0, _rsa_check_modulus_last

  # If z = n-1 (and j < a), continue with the next witness.
  la  x16, r0
  la  x17, rsa_n
  jal x1, is_pminus1
  bne x2, x0, _rsa_check_modulus_round
  jal x0, _rsa_check_modulus_square

_rsa_check_modulus_last:
  # dmem[r2] <= x = z
  la  x12, r0
  la  x13, r2
  jal x1, rsa_check_modulus_copy

_rsa_check_modulus_final:
  # Compute x-1. Here x is neither 0 nor 1, so this does not underflow.
  # dmem[r2] <= x-1
  li      x14, 2
  bn.addi w3, w31, 1
  bn.add  w31, w31, w31
  la      x12, r2
  loop    x30, 4
    bn.lid  x14, 0(x12)
    bn.subb w2, w2, w3
    bn.sid  x14, 0(x12++)
    bn.mov  w3, w31

  # dmem[r0] <= n
  la  x12, rsa_n
  la  x13, r0
  jal x1, rsa_check_modulus_copy

  # n is not a prime power iff gcd(x-1, n) = 1.
  # dmem[r0] <= gcd(x-1, n)
  la  x10, r2
  la  x11, r0
  jal x1, gcd
  la  x16, r0
  jal x1, is_1
  beq x2, x0, _rsa_check_modulus_reject

  # n is provably composite and not a power of a prime.
  addi x2, x0, HARDENED_BOOL_TRUE
  ret

_rsa_check_modulus_reject:
  addi x2, x0, HARDENED_BOOL_FALSE
  ret

/**
 * Copy an N-limb bignum within DMEM.
 *
 * @param[in] x12: dptr_src, source buffer
 * @param[in] x13: dptr_dst, destination buffer
 * @param[in] x30: N, number of limbs
 *
 * Clobbered registers: x12, x13, x14, w2
 */
rsa_check_modulus_copy:
  li   x14, 2
  loop x30, 2
    bn.lid x14, 0(x12++)
    bn.sid x14, 0(x13++)
  ret

/**
 * Montgomery multiplication modulo rsa_n with the pointer setup of `modexp`.
 *
 * @param[in]  x19: dptr_a, first operand
 * @param[in]  x20: dptr_b, second operand
 * @param[in]  x30: N, number of limbs
 * @param[in]  x31: N-1
 * @param[in]   w1: m0', Montgomery constant
 * @param[out] [w[4+N-1]:w4]: montmul(a, b)
 *
 * Clobbered registers: see `montmul`
 */
rsa_check_modulus_montmul:
  li  x8, 4
  li  x9, 3
  li  x10, 4
  li  x11, 2
  la  x16, rsa_n
  jal x1, montmul
  ret

/**
 * Store the `montmul` result [w[4+N-1]:w4] to DMEM.
 *
 * @param[in] x3: dptr_dst, destination buffer
 * @param[in] x30: N, number of limbs
 *
 * Clobbered registers: x2, x3
 */
rsa_check_modulus_store:
  li   x2, 4
  loop x30, 2
    bn.sid x2, 0(x3++)
    addi   x2, x2, 1
  ret
