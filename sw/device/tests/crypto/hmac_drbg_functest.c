/**
 * Test auto-reseed enable/disable behavior.
 */
static status_t auto_reseed_test(void) {
  LOG_INFO("Running HMAC-DRBG auto-reseed test...");
  static const uint8_t kEntropy[] = {
      0x4c, 0xc1, 0x9f, 0xae, 0x5a, 0x45, 0x6f, 0x8a, 0x53, 0xa6, 0x56,
      0xd2, 0x3a, 0x0b, 0x66, 0x5d, 0x6d, 0xdf, 0x7f, 0x43, 0x02, 0x0a,
      0x5f, 0xeb, 0xbb, 0x55, 0x27, 0x14, 0xe4, 0x47, 0x56, 0x5d};
  static const uint8_t kNonce[] = {0xaa, 0x7f, 0xd3, 0xc3, 0xdd, 0x5d,
                                   0x03, 0xd9, 0xb8, 0xef, 0xc7, 0xf7,
                                   0x05, 0x74, 0x58, 0x1f};
  static const uint8_t kPerso[] = {
      0x4b, 0xc9, 0xa4, 0x85, 0xec, 0x84, 0x0d, 0x37, 0x7a, 0xe4, 0x50,
      0x4a, 0xa1, 0xdf, 0x41, 0xe4, 0x44, 0xc4, 0x23, 0x16, 0x87, 0xf3,
      0xd7, 0x85, 0x1c, 0x26, 0xc2, 0x75, 0xbc, 0x68, 0x74, 0x63};

  otcrypto_hmac_drbg_context_t ctx;
  otcrypto_const_byte_buf_t entropy =
      OTCRYPTO_MAKE_BUF(otcrypto_const_byte_buf_t, kEntropy, sizeof(kEntropy));
  otcrypto_const_byte_buf_t nonce =
      OTCRYPTO_MAKE_BUF(otcrypto_const_byte_buf_t, kNonce, sizeof(kNonce));
  otcrypto_const_byte_buf_t perso =
      OTCRYPTO_MAKE_BUF(otcrypto_const_byte_buf_t, kPerso, sizeof(kPerso));

  TRY(otcrypto_hmac_drbg_init(&ctx, &entropy, &nonce, &perso,
                              /*reseed_interval=*/2, kOtcryptoHashModeSha256));

  // Invalid hardened_bool_t value should be rejected.
  TRY_CHECK(
      otcrypto_hmac_drbg_set_auto_reseed(&ctx, (hardened_bool_t)0x1234).value ==
      OTCRYPTO_BAD_ARGS.value);

  // Enable auto-reseed and generate 3 times (crossing reseed_interval=2).
  TRY(otcrypto_hmac_drbg_set_auto_reseed(&ctx, kHardenedBoolTrue));

  uint8_t out_byte = 0;
  otcrypto_byte_buf_t out_buf =
      OTCRYPTO_MAKE_BUF(otcrypto_byte_buf_t, &out_byte, sizeof(out_byte));
  TRY(otcrypto_hmac_drbg_generate(&ctx, &perso, &out_buf));
  TRY(otcrypto_hmac_drbg_generate(&ctx, &perso, &out_buf));
  TRY(otcrypto_hmac_drbg_generate(&ctx, &perso, &out_buf));

  // Disable auto-reseed; reseed_counter is currently 2 (<= reseed_interval=2),
  // so one more generate succeeds (incrementing reseed_counter to 3) and the
  // subsequent generate hits reseed_counter > reseed_interval and fails.
  TRY(otcrypto_hmac_drbg_set_auto_reseed(&ctx, kHardenedBoolFalse));
  TRY(otcrypto_hmac_drbg_generate(&ctx, &perso, &out_buf));
  TRY_CHECK(otcrypto_hmac_drbg_generate(&ctx, &perso, &out_buf).value ==
            OTCRYPTO_RECOV_ERR.value);

  TRY(otcrypto_hmac_drbg_deinit(&ctx));
  return OK_STATUS();
}

/**
 * Negative tests for invalid arguments and uninitialized context handling.
 */
static status_t run_negative_tests(void) {
  LOG_INFO("Running HMAC-DRBG negative tests...");
  uint8_t dummy[32] = {0};
  otcrypto_const_byte_buf_t valid_in =
      OTCRYPTO_MAKE_BUF(otcrypto_const_byte_buf_t, dummy, sizeof(dummy));
  otcrypto_const_byte_buf_t empty_in =
      OTCRYPTO_MAKE_BUF(otcrypto_const_byte_buf_t, NULL, 0);
  otcrypto_const_byte_buf_t bad_in =
      OTCRYPTO_MAKE_BUF(otcrypto_const_byte_buf_t, NULL, 4);
  otcrypto_byte_buf_t valid_out =
      OTCRYPTO_MAKE_BUF(otcrypto_byte_buf_t, dummy, sizeof(dummy));
  otcrypto_byte_buf_t bad_out = OTCRYPTO_MAKE_BUF(otcrypto_byte_buf_t, NULL, 4);

  otcrypto_hmac_drbg_context_t ctx = {0};

  // Null and bad buffer checks for init.
  TRY_CHECK(otcrypto_hmac_drbg_init(NULL, &valid_in, &valid_in, &empty_in, 10,
                                    kOtcryptoHashModeSha256)
                .value == OTCRYPTO_BAD_ARGS.value);
  TRY_CHECK(otcrypto_hmac_drbg_init(&ctx, NULL, &valid_in, &empty_in, 10,
                                    kOtcryptoHashModeSha256)
                .value == OTCRYPTO_BAD_ARGS.value);
  TRY_CHECK(otcrypto_hmac_drbg_init(&ctx, &bad_in, &valid_in, &empty_in, 10,
                                    kOtcryptoHashModeSha256)
                .value == OTCRYPTO_BAD_ARGS.value);
  TRY_CHECK(otcrypto_hmac_drbg_init(&ctx, &valid_in, &valid_in, &empty_in, 10,
                                    kOtcryptoHashModeSha3_256)
                .value == OTCRYPTO_BAD_ARGS.value);
  TRY_CHECK(otcrypto_hmac_drbg_init(&ctx, &empty_in, &valid_in, &empty_in, 10,
                                    kOtcryptoHashModeSha256)
                .value == OTCRYPTO_BAD_ARGS.value);
  TRY_CHECK(otcrypto_hmac_drbg_init(&ctx, &valid_in, &empty_in, &empty_in, 10,
                                    kOtcryptoHashModeSha256)
                .value == OTCRYPTO_BAD_ARGS.value);
  TRY_CHECK(otcrypto_hmac_drbg_init(&ctx, &valid_in, &valid_in, &empty_in, 0,
                                    kOtcryptoHashModeSha256)
                .value == OTCRYPTO_BAD_ARGS.value);

  // Operations on uninitialized context must fail.
  TRY_CHECK(otcrypto_hmac_drbg_reseed(&ctx, &valid_in, &empty_in).value ==
            OTCRYPTO_BAD_ARGS.value);
  TRY_CHECK(otcrypto_hmac_drbg_set_auto_reseed(&ctx, kHardenedBoolTrue).value ==
            OTCRYPTO_BAD_ARGS.value);
  TRY_CHECK(otcrypto_hmac_drbg_generate(&ctx, &empty_in, &valid_out).value ==
            OTCRYPTO_BAD_ARGS.value);

  // Initialize context and test bad arguments on initialized context.
  TRY(otcrypto_hmac_drbg_init(&ctx, &valid_in, &valid_in, &empty_in, 10,
                              kOtcryptoHashModeSha256));
  TRY_CHECK(otcrypto_hmac_drbg_reseed(&ctx, &empty_in, &empty_in).value ==
            OTCRYPTO_BAD_ARGS.value);
  TRY_CHECK(otcrypto_hmac_drbg_generate(&ctx, &empty_in, &bad_out).value ==
            OTCRYPTO_BAD_ARGS.value);
  TRY(otcrypto_hmac_drbg_deinit(&ctx));

  return OK_STATUS();
}

bool test_main(void) {
  status_t result = OK_STATUS();

  CHECK_STATUS_OK(otcrypto_init(kOtcryptoKeySecurityLevelLow));

  EXECUTE_TEST(result, sha256_kat_test_1);
  EXECUTE_TEST(result, sha256_kat_test_2);
  EXECUTE_TEST(result, sha384_kat_test);
  EXECUTE_TEST(result, sha512_kat_test);
  EXECUTE_TEST(result, auto_reseed_test);
  EXECUTE_TEST(result, run_negative_tests);

  return status_ok(result);
}
