/**
 * =============================================================================
 * FIPS 140-3 Known Answer Test (KAT) Vectors in ROM
 * =============================================================================
 *
 * Placement & Footprint Architecture:
 * -----------------------------------
 * All 30 KAT descriptor entries and vector payloads (covering 31 KAT
 * operations, with RSA-4096 Sign and Verify sharing a single keypair entry)
 * are grouped into a single combined struct (`kFipsKatRomBlob`, ~7.3 KiB /
 * 7,448 B total footprint) placed in `.fips_kat` and anchored by `rom.ld` at
 * the start of the fixed 8 KiB NAPOT window `[0x6E000, 0x70000)` on Earl Grey
 * Gen2, leaving 184 KiB below for Mask ROM code and read-only data with zero
 * dead gap and 616 B free before `.chip_info` at `0x6FF80`
 * (`kFipsKatMaxTableSize` = `0x1F80` = 8,064 B).
 *
 * All payload offsets are computed at compile time via
 * `offsetof(fips_kat_rom_blob_t, data.<field>)`, eliminating any possibility
 * of cross-section linker padding drift.
 *
 * Uniform Binary Payload ABI Rule:
 * --------------------------------
 * All descriptor entries (`fips_kat_entry_t`, 8 B) and payload headers use
 * uniform `uint16_t` length fields with explicit `uint16_t reserved = 0` on
 * odd-field schemas so every `data[]` array starts strictly at `0 mod 4`.
 * Every variable-length byte slice inside `data[]` is individually padded with
 * trailing `0x00` bytes to a 4-byte boundary (`FIPS_KAT_ALIGN4(len)`). Every
 * sub-field begins on a 4-byte boundary for trap-free single-word loads on
 * RISC-V Ibex and UBSan-clean word access.
 * =============================================================================
 */

