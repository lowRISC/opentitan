/**
 * Single combined ROM blob containing both the descriptor table and all
 * contiguous vector payloads, pinned at `0x6E000` in `.fips_kat`.
 */
typedef struct fips_kat_rom_blob {
  fips_kat_rom_table_t table;
  alignas(uint32_t) fips_kat_data_store_t data;
} fips_kat_rom_blob_t;

OT_ASSERT_MEMBER_OFFSET(fips_kat_rom_blob_t, table, 0);
static_assert(offsetof(fips_kat_rom_blob_t, data) % 4 == 0,
              "fips_kat_rom_blob_t.data must be 4-byte aligned");
static_assert(alignof(fips_kat_data_store_t) >= alignof(uint32_t),
              "fips_kat_data_store_t must be at least 4-byte aligned");
static_assert(alignof(fips_kat_rom_blob_t) >= alignof(uint32_t),
              "fips_kat_rom_blob_t must be at least 4-byte aligned");
static_assert(sizeof(fips_kat_rom_blob_t) % 4 == 0,
              "fips_kat_rom_blob_t must be 4-byte aligned in size");
static_assert(sizeof(fips_kat_rom_blob_t) <= kFipsKatMaxTableSize,
              "fips_kat_rom_blob_t exceeds usable 8 KiB ROM window before "
              ".chip_info");

#define FIPS_KAT_ASSERT_FIELD_ALIGN4(field)                                \
  static_assert(offsetof(fips_kat_rom_blob_t, data.field) % 4 == 0,        \
                "fips_kat_rom_blob_t.data." #field                         \
                " must start on a 4-byte boundary");                       \
  static_assert(sizeof(((fips_kat_data_store_t *)0)->field) % 4 == 0,      \
                "sizeof(data." #field ") must be a multiple of 4");        \
  static_assert(offsetof(fips_kat_rom_blob_t, data.field) <= UINT16_MAX,   \
                "offset of data." #field " exceeds uint16_t");             \
  static_assert(sizeof(((fips_kat_data_store_t *)0)->field) <= UINT16_MAX, \
                "size of data." #field " exceeds uint16_t")

